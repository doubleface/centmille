// @vitest-environment jsdom
import React from 'react'
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { App } from './App.jsx'
import { Game } from './game/Game.js'
import { loadCurrentGame, saveCurrentGame } from './storage/storage.js'

let random
beforeEach(() => {
  window.localStorage.clear()
  random = vi.spyOn(Math, 'random')
})
afterEach(() => {
  cleanup()
  window.localStorage.clear()
  vi.restoreAllMocks()
})

function seed(faces) {
  const values = faces.map(face => (face - 0.5) / 6)
  random.mockImplementation(() => {
    if (!values.length) throw new Error('Unexpected random draw')
    return values.shift()
  })
}
function mountGame(game = new Game(['Alice', 'Bob'])) {
  saveCurrentGame(game.getSnapshot())
  return render(<App />)
}
function click(name) {
  fireEvent.click(screen.getByRole('button', { name }))
}
function useVirtualDice() {
  fireEvent.click(screen.getByRole('radio', { name: 'Virtuels' }))
}
function undo() {
  click('Menu de la partie')
  fireEvent.click(screen.getByRole('menuitem', { name: /Annuler le dernier tour/ }))
}
function saved() {
  return loadCurrentGame().snapshot
}
function tray() {
  return screen.getByRole('region', { name: 'Plateau de dés virtuels' })
}

describe('parcours App → hook → Game → stockage, sans mocks métier', () => {
  it('garde le parcours physique par défaut, le retour physique et le reset', () => {
    render(<App />)
    click('Commencer la partie')
    expect(screen.getByRole('radio', { name: 'Physiques' }).checked).toBe(true)
    fireEvent.change(screen.getByLabelText('Score du tour'), { target: { value: '500' } })
    click('Valider')
    expect(saved().players[0].score).toBe(500)
    expect(screen.getByText('500')).toBeTruthy()
    useVirtualDice()
    expect(tray()).toBeTruthy()
    fireEvent.click(screen.getByRole('radio', { name: 'Physiques' }))
    expect(screen.getByLabelText('Score du tour')).toBeTruthy()
    expect(saved().diceTurn).toBeNull()
    click('Menu de la partie')
    fireEvent.click(screen.getByRole('menuitem', { name: /Recommencer/ }))
    click('Confirmer')
    expect(loadCurrentGame()).toBeNull()
    expect(screen.getByText('Nouvelle partie')).toBeTruthy()
  })

  it('réserve immédiatement, force 150 à continuer et ne fusionne pas des lancers distincts', () => {
    mountGame()
    useVirtualDice()
    expect(screen.getByRole('button', { name: 'Arrêter et marquer' }).disabled).toBe(true)
    seed([1, 5, 2, 3, 6])
    click('Lancer les 5 dés')
    expect(within(tray()).getAllByText('Gardé')).toHaveLength(2)
    expect(screen.getByText(/multiple de 100/)).toBeTruthy()
    expect(saved().diceTurn.total).toBe(150)
    expect(saved().players[0].score).toBe(0)
    expect(screen.getByRole('radio', { name: 'Physiques' }).matches(':disabled')).toBe(true)
    seed([1, 5, 2])
    click('Continuer · 3 dés')
    expect(saved().diceTurn.total).toBe(300)
    expect(within(tray()).getAllByText('Gardé')).toHaveLength(4)
    seed([1])
    click('Continuer · 1 dé')
    expect(saved().diceTurn.total).toBe(400)
    expect(screen.getByText(/Main pleine/)).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Arrêter et marquer' }).disabled).toBe(true)
    seed([1, 2, 2, 3, 6])
    click('Continuer · 5 dés')
    expect(saved().diceTurn.total).toBe(500)
    expect(within(tray()).getAllByText('Gardé')).toHaveLength(1)
    click('Arrêter et marquer')
    expect(saved().players[0].score).toBe(500)
    expect(saved().currentPlayerIndex).toBe(1)
    expect(within(tray()).getByText('Bob')).toBeTruthy()
    expect(screen.getByText('500')).toBeTruthy()
  })

  it('restaure faces/réserve/cumul au rechargement et annule la validation vers le même lancer', () => {
    let view = mountGame()
    useVirtualDice()
    seed([5, 5, 5, 2, 3])
    click('Lancer les 5 dés')
    const turn = saved().diceTurn
    view.unmount()
    seed([])
    view = render(<App />)
    expect(saved().diceTurn).toEqual(turn)
    expect(within(tray()).getAllByText('Gardé')).toHaveLength(3)
    expect(screen.getByRole('button', { name: 'Continuer · 2 dés' })).toBeTruthy()
    click('Arrêter et marquer')
    expect(saved().players[0].score).toBe(500)
    undo()
    expect(saved().players[0].score).toBe(0)
    expect(saved().currentPlayerIndex).toBe(0)
    expect(saved().diceTurn).toEqual(turn)
    click('Arrêter et marquer')
    expect(saved().players[0].score).toBe(500)
    expect(saved().events).toHaveLength(1)
    view.unmount()
  })

  it('garde la broucouille lisible jusqu’à confirmation et restaure son état après Undo', () => {
    mountGame()
    useVirtualDice()
    seed([5, 5, 5, 2, 3])
    click('Lancer les 5 dés')
    seed([2, 3])
    click('Continuer · 2 dés')
    expect(screen.getByText(/500 points perdus/)).toBeTruthy()
    expect(document.activeElement).toBe(screen.getByRole('button', { name: 'Confirmer la broucouille' }))
    expect(saved().currentPlayerIndex).toBe(0)
    expect(saved().events).toEqual([])
    click('Confirmer la broucouille')
    expect(saved().players[0].failedTurnsInRow).toBe(1)
    expect(saved().currentPlayerIndex).toBe(1)
    expect(document.activeElement).toBe(screen.getByRole('button', { name: 'Lancer les 5 dés' }))
    undo()
    expect(saved().players[0].failedTurnsInRow).toBe(0)
    expect(screen.getByText(/500 points perdus/)).toBeTruthy()
    click('Confirmer la broucouille')
    expect(saved().events).toEqual([{ type: 'bust', player: 'Alice' }])
  })

  it('ne perd pas le tour quand le générateur fournit une face invalide', () => {
    mountGame()
    useVirtualDice()
    random.mockReturnValue(1)
    click('Lancer les 5 dés')
    expect(screen.getByRole('alert').textContent).toContain('faces entières')
    expect(saved().diceTurn.phase).toBe('ready')
    seed([2, 2, 3, 4, 6])
    click('Lancer les 5 dés')
    expect(screen.queryByRole('alert')).toBeNull()
    expect(screen.getByText(/0 points perdus/)).toBeTruthy()
    click('Confirmer la broucouille')
    expect(saved().players[0].failedTurnsInRow).toBe(1)
  })

  it('bloque le plateau pendant la revue réelle d’une collision', () => {
    const game = new Game(['Alice', 'Bob'])
    game.players[1].validateTurn(500)
    mountGame(game)
    useVirtualDice()
    seed([5, 5, 5, 2, 3])
    click('Lancer les 5 dés')
    click('Arrêter et marquer')
    expect(saved().players[1].score).toBe(0)
    expect(screen.getByText(/Rétrogradation:/)).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Lancer les 5 dés' }).disabled).toBe(true)
    click('Terminer')
    expect(screen.getByRole('button', { name: 'Lancer les 5 dés' }).disabled).toBe(false)
  })

  it('bloque la relance au dépassement, attend confirmation et permet un Undo fidèle', () => {
    const game = new Game(['Alice', 'Bob'])
    game.players[0].validateTurn(9800)
    game.players[0].validateTurn(100)
    game.players[0].failedTurnsInRow = 2
    mountGame(game)
    useVirtualDice()
    seed([5, 5, 5, 2, 3])
    click('Lancer les 5 dés')
    expect(saved().currentPlayerIndex).toBe(0)
    expect(saved().players[0].failedTurnsInRow).toBe(2)
    expect(screen.getByText(/relance impossible/)).toBeTruthy()
    expect(screen.queryByRole('button', { name: /Continuer/ })).toBeNull()
    expect(saved().diceTurn.total).toBe(500)
    expect(saved().events).toEqual([])
    expect(document.activeElement).toBe(screen.getByRole('button', { name: 'Confirmer l’échec (dépassement)' }))
    click('Confirmer l’échec (dépassement)')
    expect(saved().players[0].score).toBe(9800)
    expect(saved().events).toContainEqual({ type: 'bust', player: 'Alice' })
    expect(saved().currentPlayerIndex).toBe(1)
    click('Terminer')
    undo()
    expect(saved().players[0].score).toBe(9900)
    expect(saved().players[0].failedTurnsInRow).toBe(2)
    expect(saved().diceTurn.total).toBe(500)
    expect(screen.getByRole('button', { name: 'Confirmer l’échec (dépassement)' })).toBeTruthy()
    expect(screen.queryByRole('button', { name: /Continuer/ })).toBeNull()
  })

  it.each([
    [[4, 5, 4, 5, 5], 500],
    [[5, 5, 5, 1, 2], 600],
    [[5, 5, 5, 5, 5], 2000],
    [[3, 3, 3, 1, 5], 450],
  ])('ne propose aucune relance pour %j à 9700 et confirme même hors centaine', (faces, total) => {
    const game = new Game(['Alice', 'Bob'])
    game.players[0].validateTurn(9700)
    let view = mountGame(game)
    useVirtualDice()
    seed(faces)
    click('Lancer les 5 dés')
    expect(saved().diceTurn.total).toBe(total)
    expect(saved().players[0].score).toBe(9700)
    expect(saved().currentPlayerIndex).toBe(0)
    expect(screen.queryByRole('button', { name: /Continuer|Arrêter et marquer/ })).toBeNull()
    expect(screen.queryByText(/Main pleine : relancez|Le cumul doit être un multiple/)).toBeNull()
    view.unmount()
    seed([])
    view = render(<App />)
    expect(screen.queryByRole('button', { name: /Continuer/ })).toBeNull()
    click('Confirmer l’échec (dépassement)')
    expect(saved().players[0].failedTurnsInRow).toBe(1)
    expect(saved().players[0].score).toBe(9700)
    expect(saved().currentPlayerIndex).toBe(1)
    expect(saved().diceCarry).toBeNull()
    undo()
    expect(saved().diceTurn.total).toBe(total)
    expect(saved().players[0].failedTurnsInRow).toBe(0)
    expect(screen.queryByRole('button', { name: /Continuer/ })).toBeNull()
  })

  it('ouvre grâce au cumul repris, après un lancer obligatoire, et conserve reprise et Undo', () => {
    const game = new Game(['Alice', 'Bob'])
    game.players[0].validateTurn(500)
    let view = mountGame(game)
    useVirtualDice()
    seed([2, 2, 2, 2, 3])
    click('Lancer les 5 dés')
    click('Arrêter et marquer')
    expect(saved().players[0].score).toBe(900)
    expect(saved().players[1].hasOpened).toBe(false)
    expect(screen.getByRole('button', { name: 'Arrêter et marquer' }).disabled).toBe(true)
    view.unmount()
    seed([])
    view = render(<App />)
    expect(screen.getByRole('button', { name: 'Reprendre 400 pts · lancer 1 dé' })).toBeTruthy()
    expect(saved().diceTurn.rolls).toEqual([])
    seed([5])
    click('Reprendre 400 pts · lancer 1 dé')
    expect(saved().diceTurn.total).toBe(450)
    expect(saved().diceCarry).toBeNull()
    expect(screen.getByText('dont 400 repris')).toBeTruthy()
    expect(screen.getByText(/multiple de 100.*Ouverture/)).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Arrêter et marquer' }).disabled).toBe(true)
    seed([5, 2, 2, 3, 6])
    click('Continuer · 5 dés')
    const turn = saved().diceTurn
    expect(turn.total).toBe(500)
    view.unmount()
    seed([])
    render(<App />)
    expect(saved().diceTurn).toEqual(turn)
    expect(screen.getByText('dont 400 repris')).toBeTruthy()
    click('Arrêter et marquer')
    expect(saved().players[1].score).toBe(500)
    expect(saved().players[1].hasOpened).toBe(true)
    expect(saved().events.at(-1)).toEqual({ type: 'score', player: 'Bob', turnScore: 500, cumulative: 500 })
    undo()
    expect(saved().players[1].score).toBe(0)
    expect(saved().players[1].hasOpened).toBe(false)
    expect(saved().diceTurn).toEqual(turn)
  })

  it('perd le cumul repris à la broucouille, sans annuler le score du joueur précédent', () => {
    mountGame()
    useVirtualDice()
    seed([5, 5, 5, 2, 3])
    click('Lancer les 5 dés')
    click('Arrêter et marquer')
    seed([2, 3])
    click('Reprendre 500 pts · lancer 2 dés')
    expect(screen.getByText(/500 points perdus/)).toBeTruthy()
    expect(saved().diceTurn.phase).toBe('bust')
    expect(saved().players[0].score).toBe(500)
    click('Confirmer la broucouille')
    expect(saved().players[1].score).toBe(0)
    expect(saved().players[1].hasOpened).toBe(false)
    expect(saved().players[1].failedTurnsInRow).toBe(1)
    expect(screen.queryByRole('button', { name: /Reprendre/ })).toBeNull()
  })

  it('peut refuser une reprise avec un nouveau lancer de cinq dés', () => {
    mountGame()
    useVirtualDice()
    seed([1, 2, 3, 4, 5])
    click('Lancer les 5 dés')
    click('Arrêter et marquer')
    expect(screen.getByRole('button', { name: 'Reprendre 1500 pts · lancer 5 dés' })).toBeTruthy()
    seed([1, 2, 2, 3, 6])
    click('Lancer les 5 dés')
    expect(saved().diceTurn.total).toBe(100)
    expect(saved().diceTurn.inheritedRolls).toEqual([])
    expect(saved().diceCarry).toBeNull()
    expect(screen.queryByText(/repris/)).toBeNull()
  })

  it('arrête le jeu à la victoire exacte', () => {
    const game = new Game(['Alice', 'Bob'])
    game.players[0].validateTurn(9900)
    mountGame(game)
    useVirtualDice()
    seed([1, 2, 2, 3, 6])
    click('Lancer les 5 dés')
    click('Arrêter et marquer')
    expect(saved().players[0].score).toBe(10000)
    expect(screen.getByRole('complementary').textContent).toContain('Alice')
    expect(screen.getByRole('button', { name: 'Lancer les 5 dés' }).disabled).toBe(true)
    undo()
    expect(screen.queryByRole('complementary')).toBeNull()
    expect(saved().players[0].score).toBe(9900)
    expect(saved().diceTurn.total).toBe(100)
  })

  it.each(['cent-mille', 'dix-mille-bonus'])('annonce la limite bonus provisoire et conserve la saisie %s', mode => {
    mountGame(new Game(['Alice', 'Bob'], { mode }))
    expect(screen.getByRole('radio', { name: 'Virtuels' }).disabled).toBe(true)
    expect(screen.getByText(/Dés virtuels Bonus en préparation/)).toBeTruthy()
    expect(screen.getByLabelText('Score du tour')).toBeTruthy()
  })
})
